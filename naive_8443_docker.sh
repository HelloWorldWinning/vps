#!/usr/bin/env bash
#
# naive_maneger.sh - interactive manager for pocat/naiveproxy (Caddy v2) via docker compose
#
#   bash naive_maneger.sh
#
# TLS: certificates stay managed by acme.sh. This script picks ONE of your
# acme.sh domains and uses `acme.sh --install-cert` to copy its fullchain/key
# into ${naive_path}/certs and registers a --reloadcmd so that future renewals
# automatically restart the container. That cert dir is then mapped (mounted)
# into the container. Only the chosen domain is mapped, never all of them.
#
# Networking: the container runs with `network_mode: host`. Caddy binds
# ${PORT} (tcp + udp/h3) directly on the host -- there is no "PORT:443"
# docker port mapping. Reason: on a docker bridge the container only gets a
# private ULA IPv6 (fd00::/8) behind NAT66, and Go/Caddy's RFC 6724 address
# selection then prefers IPv4 for every dual-stack destination. On the host
# network Caddy sees the real global IPv6 and uses it normally. It also removes
# docker-proxy from the path (UDP/QUIC, IPv6 inbound) and logs real client IPs.
#
set -u

# --------------------------------------------------------------------------- #
# Paths (as requested)
# --------------------------------------------------------------------------- #
naive_path=/root/naive_d_8443
yml_path=${naive_path}/docker-compose.yml

conf_path=${naive_path}/naive.conf
caddy_path=${naive_path}/Caddyfile
cert_dir=${naive_path}/certs
www_dir=${naive_path}/www
log_dir=${naive_path}/log

CONTAINER=naiveproxy
DEFAULT_IMAGE=pocat/naiveproxy:latest

# --------------------------------------------------------------------------- #
# Pretty output
# --------------------------------------------------------------------------- #
if [ -t 1 ]; then
	C_R=$'\033[31m'
	C_G=$'\033[32m'
	C_Y=$'\033[33m'
	C_B=$'\033[36m'
	C_0=$'\033[0m'
else
	C_R=
	C_G=
	C_Y=
	C_B=
	C_0=
fi
info() { printf '%s[*]%s %s\n' "$C_B" "$C_0" "$*"; }
ok() { printf '%s[+]%s %s\n' "$C_G" "$C_0" "$*"; }
warn() { printf '%s[!]%s %s\n' "$C_Y" "$C_0" "$*"; }
err() { printf '%s[x]%s %s\n' "$C_R" "$C_0" "$*" >&2; }
hr() { printf '%s\n' "------------------------------------------------------------"; }

pause() { read -rp "Press Enter to continue..." _ || true; }

# --------------------------------------------------------------------------- #
# Environment detection
# --------------------------------------------------------------------------- #
DC=""        # docker compose command
ACME_BIN=""  # path to acme.sh
ACME_HOME="" # acme.sh data dir

detect_root() {
	if [ "$(id -u)" -ne 0 ]; then
		err "Please run as root (acme.sh certs and ${naive_path} live under /root)."
		exit 1
	fi
}

detect_docker() {
	if ! command -v docker >/dev/null 2>&1; then
		warn "docker not found."
		read -rp "Install docker now via get.docker.com? [y/N]: " a
		case "$a" in
		y | Y)
			curl -fsSL https://get.docker.com | sh || {
				err "docker install failed"
				exit 1
			}
			systemctl enable --now docker 2>/dev/null || true
			;;
		*)
			err "docker is required. Aborting."
			exit 1
			;;
		esac
	fi
	if docker compose version >/dev/null 2>&1; then
		DC="docker compose"
	elif command -v docker-compose >/dev/null 2>&1; then
		DC="docker-compose"
	else
		err "docker compose plugin not found. Install it and retry."
		exit 1
	fi
}

detect_acme() {
	if command -v acme.sh >/dev/null 2>&1; then
		ACME_BIN="$(command -v acme.sh)"
	elif [ -x "/root/.acme.sh/acme.sh" ]; then
		ACME_BIN="/root/.acme.sh/acme.sh"
	elif [ -x "${HOME}/.acme.sh/acme.sh" ]; then
		ACME_BIN="${HOME}/.acme.sh/acme.sh"
	fi
	if [ -d "/root/.acme.sh" ]; then
		ACME_HOME="/root/.acme.sh"
	else
		ACME_HOME="${HOME}/.acme.sh"
	fi
}

# --------------------------------------------------------------------------- #
# Config helpers
# --------------------------------------------------------------------------- #
is_installed() { [ -f "$conf_path" ]; }

load_conf() {
	if ! is_installed; then
		err "Not installed yet. Run install (option 1) first."
		return 1
	fi
	# shellcheck disable=SC1090
	. "$conf_path"
}

save_conf() {
	mkdir -p "$naive_path"
	# probe_resistance must be lowercase to be visitable; normalize defensively.
	SECRET="$(printf '%s' "$SECRET" | tr '[:upper:]' '[:lower:]')"
	cat >"$conf_path" <<EOF
# Generated by naive_maneger.sh
DOMAIN='${DOMAIN}'
PORT='${PORT}'
NAIVE_USER='${NAIVE_USER}'
NAIVE_PASS='${NAIVE_PASS}'
SECRET='${SECRET}'
IMAGE='${IMAGE}'
ECC='${ECC}'
EOF
	chmod 600 "$conf_path"
}

rand_secret() {
	# lowercase only: Caddy warns that uppercase probe_resistance domains
	# "are not visitable".
	local s
	s="$(head -c 24 /dev/urandom | base64 2>/dev/null | tr '[:upper:]' '[:lower:]' | tr -dc 'a-z0-9' | head -c 14)"
	[ -z "$s" ] && s="secret$(date +%s)"
	printf '%s.com' "$s"
}

# --------------------------------------------------------------------------- #
# acme.sh: pick a domain & install (map) its cert
# --------------------------------------------------------------------------- #
# acme.sh stores how each cert is renewed in Le_Webroot of its .conf file.
# acme_conf_file <domain>  -> path of that .conf (ECC dir preferred)
acme_conf_file() {
	local d="$1"
	if [ -f "${ACME_HOME}/${d}_ecc/${d}.conf" ]; then
		printf '%s' "${ACME_HOME}/${d}_ecc/${d}.conf"
	elif [ -f "${ACME_HOME}/${d}/${d}.conf" ]; then
		printf '%s' "${ACME_HOME}/${d}/${d}.conf"
	fi
}

# renew_method <domain>  -> one of: dns:<api> | standalone | alpn | webserver | webroot | unknown
renew_method() {
	local f w
	f="$(acme_conf_file "$1")"
	[ -n "$f" ] || {
		echo unknown
		return
	}
	w="$(sed -n "s/^Le_Webroot='\{0,1\}\([^',]*\).*/\1/p" "$f" | head -n1)"
	case "$w" in
	dns*) echo "dns:${w}" ;;
	no) echo standalone ;;
	alpn) echo alpn ;;
	apache | nginx*) echo webserver ;;
	/*) echo webroot ;;
	*) echo unknown ;;
	esac
}

# Human description of which port (if any) a renewal of <domain> needs.
renew_ports_desc() {
	case "$(renew_method "$1")" in
	dns:*) echo "DNS-01 ($(renew_method "$1" | cut -d: -f2-)) - no ports needed" ;;
	standalone) echo "standalone HTTP-01 - NEEDS port 80 free" ;;
	alpn) echo "TLS-ALPN-01 - NEEDS port 443 free" ;;
	webserver) echo "apache/nginx mode - uses port 80 via that web server" ;;
	webroot) echo "webroot HTTP-01 - needs a web server on port 80" ;;
	*) echo "unknown method" ;;
	esac
}

pick_domain() {
	if [ -z "$ACME_BIN" ]; then
		err "acme.sh not found. Install/issue a cert with acme.sh first."
		return 1
	fi
	local domains=()
	mapfile -t domains < <("$ACME_BIN" --list 2>/dev/null | awk 'NR>1 && NF>0 {print $1}')
	if [ "${#domains[@]}" -eq 0 ]; then
		err "No certificates registered in acme.sh ($ACME_BIN --list is empty)."
		return 1
	fi
	echo "acme.sh domains:"
	local i=1 d
	for d in "${domains[@]}"; do
		printf '  %d) %-28s renew: %s\n' "$i" "$d" "$(renew_ports_desc "$d")"
		i=$((i + 1))
	done
	local choice
	while :; do
		read -rp "Pick the domain to use [1-${#domains[@]}]: " choice
		if [[ "$choice" =~ ^[0-9]+$ ]] && [ "$choice" -ge 1 ] && [ "$choice" -le "${#domains[@]}" ]; then
			DOMAIN="${domains[$((choice - 1))]}"
			break
		fi
		warn "Invalid choice."
	done
	# ECC vs RSA -> acme.sh needs --ecc for EC certs
	if [ -d "${ACME_HOME}/${DOMAIN}_ecc" ]; then ECC="--ecc"; else ECC=""; fi
	ok "Selected: ${DOMAIN}  (${ECC:-rsa})"
	info "This script only COPIES the existing cert (acme.sh --install-cert): no port 80/443 used."
	case "$(renew_method "$DOMAIN")" in
	dns:*) ;;
	*) warn "acme.sh's own renewal of ${DOMAIN}: $(renew_ports_desc "$DOMAIN")." ;;
	esac
}

install_cert() {
	mkdir -p "$cert_dir"
	info "Installing/mapping cert for ${DOMAIN} via acme.sh ..."
	# The reloadcmd runs on every renewal so Caddy picks up the new cert.
	"$ACME_BIN" --install-cert -d "$DOMAIN" ${ECC} \
		--fullchain-file "${cert_dir}/fullchain.cer" \
		--key-file "${cert_dir}/private.key" \
		--reloadcmd "docker restart ${CONTAINER} >/dev/null 2>&1 || true"
	if [ ! -s "${cert_dir}/fullchain.cer" ] || [ ! -s "${cert_dir}/private.key" ]; then
		err "Cert install did not produce files in ${cert_dir}."
		return 1
	fi
	ok "Cert mapped into ${cert_dir} (auto-updated on renewal)."
}

# --------------------------------------------------------------------------- #
# File generators
# --------------------------------------------------------------------------- #
gen_caddyfile() {
	# Caddyfile body is tab-indented so Caddy does not warn "input is not formatted".
	cat >"$caddy_path" <<EOF
{
	admin off
	# Host network: "off" = no ACME (certs come from acme.sh) AND no HTTP->HTTPS
	# redirect listener, which would otherwise try to bind host port :80.
	auto_https off
	log {
		output file /var/log/caddy/access.log
		level INFO
	}
	servers :${PORT} {
		protocols h1 h2 h3
	}
}

# Caddy binds ${PORT} (tcp + udp/h3) directly on the host, dual-stack.
https://:${PORT} {
	tls /etc/naiveproxy/certs/fullchain.cer /etc/naiveproxy/certs/private.key
	route {
		forward_proxy {
			basic_auth "${NAIVE_USER}" "${NAIVE_PASS}"
			hide_ip
			hide_via
			probe_resistance ${SECRET}
		}
		file_server {
			root /var/www/html
		}
	}
}
EOF
	ok "Wrote ${caddy_path}"
}

gen_compose() {
	cat >"$yml_path" <<EOF
services:
  naiveproxy:
    image: ${IMAGE}
    container_name: ${CONTAINER}
    restart: always
    # host networking: the container uses the VPS's real global IPv6 instead of
    # a Docker ULA + NAT66 address. With ULA, Go (Caddy) prefers IPv4 for every
    # dual-stack destination (RFC 6724), so IPv6 was only used for v6-only sites.
    network_mode: host
    volumes:
      - ${naive_path}:/etc/naiveproxy
      - ${www_dir}:/var/www/html
      - ${log_dir}:/var/log/caddy
    environment:
      # The pocat/naiveproxy image uses PATH to locate its config file.
      - PATH=/etc/naiveproxy/Caddyfile
EOF
	ok "Wrote ${yml_path}"
}

# --------------------------------------------------------------------------- #
# Compose actions
# --------------------------------------------------------------------------- #
compose() { $DC -f "$yml_path" "$@"; }

# True if the existing compose file is the old bridge + port-mapping layout.
is_legacy_layout() { [ -f "$yml_path" ] && ! grep -q 'network_mode: host' "$yml_path"; }

# Names of processes listening on a port (tcp or udp), space separated.
port_owner() {
	command -v ss >/dev/null 2>&1 || return 0
	ss -Hlntup "( sport = :$1 )" 2>/dev/null |
		grep -o 'users:(("[^"]*"' | sed 's/.*"//' | sort -u | tr '\n' ' '
}

# Return 0 if the port is free on the host, or held by our own naiveproxy
# container (caddy in host mode, docker-proxy in the old bridge layout).
check_port() {
	local owner
	owner="$(port_owner "$1")"
	[ -z "$owner" ] && return 0
	if docker ps -q -f "name=^${CONTAINER}$" | grep -q . &&
		printf '%s' "$owner" | grep -Eqw 'caddy|docker-proxy'; then
		return 0
	fi
	warn "Port $1 is already in use on this host by: ${owner}"
	return 1
}

# ask_port <default>  -> sets PORT (valid range, and free on the host)
ask_port() {
	local def="$1" p
	while :; do
		read -rp "Listen port [${def}]: " p
		p="${p:-$def}"
		if ! [[ "$p" =~ ^[0-9]+$ ]] || [ "$p" -lt 1 ] || [ "$p" -gt 65535 ]; then
			warn "Port must be 1-65535."
			continue
		fi
		check_port "$p" || continue
		PORT="$p"
		return 0
	done
}

firewall_hint() {
	if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q 'Status: active'; then
		if ! ufw status 2>/dev/null | grep -qw "${PORT}"; then
			warn "ufw is active and has no rule for ${PORT}. Run:"
			warn "  ufw allow ${PORT}/tcp && ufw allow ${PORT}/udp"
		fi
	else
		info "Host network mode: docker no longer opens ports for you."
		info "If you run a firewall, allow ${PORT}/tcp and ${PORT}/udp."
	fi
}

# Wait briefly, then confirm the container is up and not crash-looping.
# The container is freshly created by every caller, so any restart within the
# wait window means Caddy crashed on startup (restart: always hides that).
verify_running() {
	sleep 4
	local state
	state="$(docker inspect -f '{{.State.Running}} {{.State.Restarting}} {{.RestartCount}}' "$CONTAINER" 2>/dev/null)"
	if [ "$state" = "true false 0" ]; then
		return 0
	fi
	err "Container ${CONTAINER} is not running cleanly (running/restarting/restarts: ${state:-n/a})."
	# Caddy redirects its own log (including startup errors) to access.log,
	# so `docker logs` is usually empty. Show the last errors from the file.
	if [ -f "${log_dir}/access.log" ]; then
		err "Last errors in ${log_dir}/access.log:"
		grep '"level":"error"' "${log_dir}/access.log" | tail -n 3 >&2 || true
	fi
	docker logs --tail 10 "$CONTAINER" 2>&1 || true
	return 1
}

# apply_stack [pull]
# Stops the old stack (needed when switching bridge -> host so the old
# container and its network are removed), regenerates Caddyfile + compose
# from naive.conf, starts the container and verifies it.
apply_stack() {
	if [ "${1:-}" = "pull" ]; then
		info "Pulling ${IMAGE} ..."
		docker pull "$IMAGE" || warn "Pull failed; using the local image if present."
	fi
	if [ -f "$yml_path" ]; then
		compose down --remove-orphans >/dev/null 2>&1 || true
	fi
	# in case a container with this name exists outside this compose project
	docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
	gen_caddyfile
	gen_compose
	compose up -d || return 1
	if ! verify_running; then
		# stop the restart loop so it does not keep spamming the log
		compose stop >/dev/null 2>&1 || true
		warn "Container stopped. Fix the error above, then run option 8 (or 6 to start)."
		return 1
	fi
	firewall_hint
}

# --------------------------------------------------------------------------- #
# Connection info
# --------------------------------------------------------------------------- #
show_link() {
	load_conf || return 1
	hr
	printf '%sNaiveProxy connection info%s\n' "$C_G" "$C_0"
	hr
	printf 'Server   : %s\n' "$DOMAIN"
	printf 'Port     : %s\n' "$PORT"
	printf 'Username : %s\n' "$NAIVE_USER"
	printf 'Password : %s\n' "$NAIVE_PASS"
	printf 'Decoy    : %s  (probe_resistance / fake host)\n' "$SECRET"
	echo
	echo "Proxy URL:"
	printf '  %shttps://%s:%s@%s:%s%s\n' "$C_B" "$NAIVE_USER" "$NAIVE_PASS" "$DOMAIN" "$PORT" "$C_0"
	echo
	echo "naive client config.json:"
	cat <<JSON
  {
    "listen": "socks://127.0.0.1:1080",
    "proxy": "https://${NAIVE_USER}:${NAIVE_PASS}@${DOMAIN}:${PORT}"
  }
JSON
	echo
	echo "Share link (SagerNet / NekoBox / sing-box):"
	printf '  naive+https://%s:%s@%s:%s?padding=true#%s\n' \
		"$NAIVE_USER" "$NAIVE_PASS" "$DOMAIN" "$PORT" "$DOMAIN"
	hr
	warn "If user/pass contains special characters, URL-encode them in the link."
}

# --------------------------------------------------------------------------- #
# Prompts
# --------------------------------------------------------------------------- #
prompt_settings() {
	local p
	ask_port 8443
	read -rp "Username [user]: " p
	NAIVE_USER="${p:-user}"
	read -rp "Password [8443]: " p
	NAIVE_PASS="${p:-8443}"
}

# --------------------------------------------------------------------------- #
# Menu actions
# --------------------------------------------------------------------------- #
do_install() {
	if is_installed; then
		warn "Already installed."
		read -rp "Reinstall / overwrite config? [y/N]: " a
		case "$a" in y | Y) ;; *) return 0 ;; esac
	fi

	IMAGE="$DEFAULT_IMAGE"
	read -rp "Enable UDP-over-TCP image (latest-uot)? [y/N]: " a
	case "$a" in y | Y) IMAGE="pocat/naiveproxy:latest-uot" ;; esac

	pick_domain || {
		pause
		return 1
	}
	prompt_settings
	SECRET="$(rand_secret)"

	mkdir -p "$naive_path" "$cert_dir" "$www_dir" "$log_dir"
	# a tiny decoy page for file_server
	[ -f "${www_dir}/index.html" ] || echo "<h1>It works.</h1>" >"${www_dir}/index.html"

	install_cert || {
		pause
		return 1
	}
	save_conf
	apply_stack pull || {
		pause
		return 1
	}

	echo
	ok "NaiveProxy is up (host network, listening on ${PORT} tcp+udp)."
	show_link
	pause
}

do_update() {
	load_conf || {
		pause
		return 1
	}
	if is_legacy_layout; then
		warn "Old bridge/port-mapping layout detected -> migrating to host network."
		apply_stack pull || {
			pause
			return 1
		}
	else
		info "Pulling latest image ..."
		compose pull
		compose up -d --force-recreate
		verify_running || {
			pause
			return 1
		}
	fi
	docker image prune -f >/dev/null 2>&1 || true
	ok "Updated."
	pause
}

do_show() {
	show_link
	echo
	echo "Files:"
	printf '  compose : %s\n' "$yml_path"
	printf '  caddy   : %s\n' "$caddy_path"
	printf '  certs   : %s\n' "$cert_dir"
	printf '  conf    : %s\n' "$conf_path"
	pause
}

do_restart() {
	load_conf || {
		pause
		return 1
	}
	compose restart
	ok "Restarted."
	pause
}
do_stop() {
	load_conf || {
		pause
		return 1
	}
	compose stop
	ok "Stopped."
	pause
}
do_start() {
	load_conf || {
		pause
		return 1
	}
	compose up -d
	ok "Started."
	pause
}

do_logs() {
	load_conf || {
		pause
		return 1
	}
	info "Following logs (Ctrl-C to exit) ..."
	compose logs -f --tail=100 || true
}

do_status() {
	load_conf || {
		pause
		return 1
	}
	compose ps
	if is_legacy_layout; then
		warn "Old bridge/port-mapping layout -> run option 2 or 8 to migrate to host network."
	fi
	echo
	info "Listening on ${PORT}:"
	if command -v ss >/dev/null 2>&1; then
		ss -Hlntup "( sport = :${PORT} )" 2>/dev/null || true
	fi
	echo
	info "Egress (host network = what proxied sites see):"
	if command -v curl >/dev/null 2>&1; then
		printf '  IPv4: %s\n' "$(curl -s4 -m 5 https://api4.ipify.org 2>/dev/null || echo 'n/a')"
		printf '  IPv6: %s\n' "$(curl -s6 -m 5 https://api6.ipify.org 2>/dev/null || echo 'n/a')"
	fi
	echo
	info "Cert expiry:"
	if command -v openssl >/dev/null 2>&1 && [ -f "${cert_dir}/fullchain.cer" ]; then
		openssl x509 -enddate -noout -in "${cert_dir}/fullchain.cer" 2>/dev/null || true
	fi
	echo
	info "acme.sh auto-renew hook for ${DOMAIN}:"
	if [ -n "$ACME_BIN" ]; then
		"$ACME_BIN" --info -d "$DOMAIN" ${ECC} 2>/dev/null |
			grep -E 'Le_Real|Le_ReloadCmd' || warn "No install-cert hook found (run option 9)."
		if crontab -l 2>/dev/null | grep -q acme.sh; then
			ok "acme.sh renewal cron is present."
		else
			warn "No acme.sh cron found -> run: $ACME_BIN --install-cronjob"
		fi
	fi
	pause
}

do_settings() {
	load_conf || {
		pause
		return 1
	}
	echo "Leave blank to keep current value."
	local old_domain="$DOMAIN" p

	read -rp "Change domain? current [${DOMAIN}] [y/N]: " a
	case "$a" in y | Y) pick_domain || {
		pause
		return 1
	} ;; esac

	ask_port "$PORT"
	read -rp "Username [${NAIVE_USER}]: " p
	NAIVE_USER="${p:-$NAIVE_USER}"
	read -rp "Password [${NAIVE_PASS}]: " p
	NAIVE_PASS="${p:-$NAIVE_PASS}"
	read -rp "Regenerate decoy domain? current [${SECRET}] [y/N]: " a
	case "$a" in y | Y) SECRET="$(rand_secret)" ;; esac

	if [ "$DOMAIN" != "$old_domain" ]; then
		install_cert || {
			pause
			return 1
		}
	fi

	save_conf
	apply_stack || {
		pause
		return 1
	}
	ok "Settings applied."
	show_link
	pause
}

do_cert() {
	load_conf || {
		pause
		return 1
	}
	# Default: only re-copy the current cert from acme.sh (local files, no ports).
	# Forcing a renewal is opt-in because it uses the cert's original issue
	# method, which may need port 80 (standalone/webroot) or 443 (alpn).
	info "Renewal method for ${DOMAIN}: $(renew_ports_desc "$DOMAIN")"
	read -rp "Also force an acme.sh renewal now? [y/N]: " a
	case "$a" in
	y | Y)
		info "Forcing acme.sh renew for ${DOMAIN} ..."
		"$ACME_BIN" --renew -d "$DOMAIN" ${ECC} --force || warn "Renew failed (current cert is kept)."
		;;
	*) info "Skipping renewal; re-copying the current cert only." ;;
	esac
	# install_cert's reloadcmd restarts the container
	install_cert || {
		pause
		return 1
	}
	ok "Cert refreshed."
	pause
}

do_uninstall() {
	load_conf || {
		pause
		return 1
	}
	warn "This stops the container and removes ${naive_path}."
	read -rp "Type 'yes' to confirm: " a
	[ "$a" = "yes" ] || {
		info "Cancelled."
		pause
		return 0
	}
	compose down 2>/dev/null || true
	# remove the acme.sh reloadcmd mapping for this domain (best effort)
	rm -rf "$naive_path"
	ok "Removed. (acme.sh certificate itself is left intact.)"
	pause
}

# --------------------------------------------------------------------------- #
# Menu
# --------------------------------------------------------------------------- #
menu() {
	while :; do
		clear 2>/dev/null || true
		hr
		printf '  %sNaiveProxy Manager%s   (%s)\n' "$C_G" "$C_0" "$naive_path"
		hr
		if is_installed; then
			printf '  status: %sinstalled%s  domain: %s  port: %s\n' "$C_G" "$C_0" \
				"$(
					. "$conf_path"
					echo "$DOMAIN"
				)" "$(
					. "$conf_path"
					echo "$PORT"
				)"
			if is_legacy_layout; then
				printf '  network: %sbridge (legacy) -> run 2 or 8 to migrate to host%s\n' "$C_Y" "$C_0"
			else
				printf '  network: %shost%s\n' "$C_G" "$C_0"
			fi
		else
			printf '  status: %snot installed%s\n' "$C_Y" "$C_0"
		fi
		hr
		cat <<MENU
  1) Install
  2) Update (pull latest & recreate)
