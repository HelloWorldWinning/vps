#!/usr/bin/env bash
# v4_v6_temporary_switcher.sh
# Temporarily reject NEW outbound connections on one IP family (Debian, nftables + systemd).
#
#   bash <(curl -LS https://raw.githubusercontent.com/<user>/<repo>/<commit>/v4_v6_temporary_switcher.sh) [4|6|0|status] [minutes]
#
#   4        keep IPv4: reject new outbound IPv6 connections
#   6        keep IPv6: reject new outbound IPv4 connections
#   0        remove the switch now and cancel its timer
#   status   show mode, timer and connectivity; change nothing
#   minutes  duration for 4 or 6 (default 180, range 1-10080)
#
# No arguments: interactive. Each prompt waits 5 seconds; Enter or timeout picks the
# default (mode 4; mode 6 on an IPv6-only host; 180 minutes). Any argument skips all prompts.
#
# Inbound connections on both families keep working: only packets that conntrack marks
# "new" in the "original" direction are rejected, so replies to inbound clients pass.
#
# Nothing survives a reboot: the nft table lives in kernel memory, the cleanup timer is
# a transient systemd unit, and every file this script writes is under /run (tmpfs).
# The script installs no packages and edits nothing under /etc.

set -uo pipefail
umask 077

readonly TOOL=v46switch
readonly TABLE=v46switch
readonly RUNDIR=/run/v46switch
readonly STATE=$RUNDIR/state.env
readonly LOCK=$RUNDIR/lock
readonly CLEANUP=$RUNDIR/cleanup.sh
readonly PROMPT_TIMEOUT=5
readonly DEFAULT_MINUTES=180
readonly MAX_MINUTES=10080
readonly CONNECT_TIMEOUT=3
readonly PROBE_TIMEOUT=5
readonly V4_TARGET=1.1.1.1
readonly V6_TARGET=2606:4700:4700::1111

PROBE_DIR=
cleanup_tmp() { if [[ -n $PROBE_DIR && -d $PROBE_DIR ]]; then rm -rf -- "$PROBE_DIR"; fi; return 0; }
trap cleanup_tmp EXIT

die()  { printf 'error: %s\n' "$*" >&2; exit 1; }
warn() { printf 'warning: %s\n' "$*" >&2; }
say()  { printf '%s\n' "$*"; }

usage() {
	cat <<'EOF'
Usage: bash <(curl -LS URL) [4|6|0|status] [minutes]
  4        keep IPv4: reject new outbound IPv6 connections
  6        keep IPv6: reject new outbound IPv4 connections
  0        remove the switch now and cancel its timer
  status   show mode, timer and connectivity; change nothing
  minutes  duration for 4 or 6 (default 180, range 1-10080)
No arguments: interactive, 5-second prompts, defaults mode 4 (6 on IPv6-only hosts) and 180 min.
EOF
}

mode_desc() {
	case $1 in
		4) printf 'IPv4 only: new outbound IPv6 rejected' ;;
		6) printf 'IPv6 only: new outbound IPv4 rejected' ;;
		*) printf 'unknown' ;;
	esac
}
fmt_time() { date -d "@$1" '+%Y-%m-%d %H:%M:%S %Z'; }
fmt_dur() {
	local s=$1 h m
	((s < 0)) && s=0
	h=$((s / 3600)); m=$((s % 3600 / 60)); s=$((s % 60))
	printf '%dh %02dm %02ds' "$h" "$m" "$s"
}
valid_minutes() { [[ $1 =~ ^[0-9]{1,6}$ ]] && ((10#$1 >= 1 && 10#$1 <= MAX_MINUTES)); }

require_env() {
	[[ $EUID -eq 0 ]] || die "run as root"
	[[ -d /run/systemd/system ]] || die "systemd is not running as PID 1; the cleanup timer needs systemd"
	local c missing=()
	for c in nft systemd-run systemctl curl flock ip sed awk od grep date; do
		command -v "$c" >/dev/null 2>&1 || missing+=("$c")
	done
	((${#missing[@]} == 0)) || die "missing commands: ${missing[*]} (install them yourself, e.g. 'apt install nftables'; this script installs nothing)"
}

ensure_rundir() { { mkdir -p "$RUNDIR" && chmod 700 "$RUNDIR"; } || die "cannot create $RUNDIR"; }

# The cleanup action run by the timer. Local file, so expiry needs no download.
write_cleanup() {
	cat >"$CLEANUP.tmp" <<'EOF'
#!/bin/sh
# v46switch cleanup. Generated by v4_v6_temporary_switcher.sh; lives in /run, gone after reboot.
#   sh /run/v46switch/cleanup.sh <id>     remove the restriction only if it is still <id> (timer use)
#   sh /run/v46switch/cleanup.sh --force  remove any restriction made by this tool and cancel all its timers
PATH=/usr/sbin:/usr/bin:/sbin:/bin
want=${1:-}
[ -n "$want" ] || { echo "usage: $0 <id>|--force" >&2; exit 2; }
mkdir -p -m 700 /run/v46switch
exec 9>/run/v46switch/lock
flock -w 60 9 || { echo "v46switch: lock busy, nothing removed" >&2; exit 1; }
cur=
if nft list table inet v46switch >/dev/null 2>&1; then
	c=$(nft list table inet v46switch 2>/dev/null | sed -n 's/^[[:space:]]*comment "\(.*\)".*$/\1/p' | head -n 1)
	case "$c" in
		"v46switch "*) cur=$(printf '%s\n' "$c" | sed -n 's/.* id=\([^ ]*\).*/\1/p') ;;
		*) echo "v46switch: table inet v46switch was not created by this tool; left untouched" >&2 ;;
	esac
fi
if [ -n "$cur" ] && { [ "$want" = "--force" ] || [ "$want" = "$cur" ]; }; then
	nft delete table inet v46switch && echo "v46switch: restriction $cur removed"
fi
if [ -f /run/v46switch/state.env ]; then
	sid=$(sed -n 's/^ID=//p' /run/v46switch/state.env)
	if [ "$want" = "--force" ] || [ "$sid" = "$want" ]; then rm -f /run/v46switch/state.env; fi
fi
if [ "$want" = "--force" ]; then
	for t in $(systemctl list-units --all --plain --no-legend --type=timer 'v46switch-*.timer' 2>/dev/null | awk '{print $1}'); do
		systemctl stop "$t" 2>/dev/null
	done
else
	# Unload this run's own transient timer (it would otherwise stay loaded as "elapsed" until reboot).
	systemctl stop --no-block "v46switch-$want.timer" 2>/dev/null
fi
exit 0
EOF
	{ chmod 700 "$CLEANUP.tmp" && mv -f "$CLEANUP.tmp" "$CLEANUP"; } || die "cannot write $CLEANUP"
}

# ---------- live state ----------
LIVE_STATE=none LIVE_ID='' LIVE_MODE='' LIVE_EXP=''
field() { local re="(^| )$1=([^ ]*)"; if [[ $2 =~ $re ]]; then printf '%s' "${BASH_REMATCH[2]}"; fi; }
read_live() {
	LIVE_STATE=none LIVE_ID='' LIVE_MODE='' LIVE_EXP=''
	nft list table inet "$TABLE" >/dev/null 2>&1 || return 0
	local c
	c=$(nft list table inet "$TABLE" 2>/dev/null | sed -n 's/^[[:space:]]*comment "\(.*\)".*$/\1/p' | head -n 1)
	if [[ $c == "$TOOL "* ]]; then
		LIVE_STATE=ours
		LIVE_ID=$(field id "$c"); LIVE_MODE=$(field mode "$c"); LIVE_EXP=$(field expiry "$c")
	else
		LIVE_STATE=foreign
	fi
}

S_ID='' S_MODE='' S_CAP4='' S_CAP6=''
load_state() {
	S_ID='' S_MODE='' S_CAP4='' S_CAP6=''
	[[ -f $STATE ]] || return 0
	local k v
	while IFS='=' read -r k v; do
		case $k in
			ID) S_ID=$v ;; MODE) S_MODE=$v ;;
			CAP4) S_CAP4=$v ;; CAP6) S_CAP6=$v ;;
		esac
	done <"$STATE"
}

write_state() { # id mode start expiry minutes
	cat >"$STATE.tmp" <<EOF
ID=$1
MODE=$2
START=$3
EXPIRY=$4
MINUTES=$5
CAP4=${CAP[4]}
CAP6=${CAP[6]}
EOF
	mv -f "$STATE.tmp" "$STATE"
}

list_timers() { systemctl list-units --all --plain --no-legend --type=timer "$TOOL-*.timer" 2>/dev/null | awk '{print $1}'; }

print_status() {
	read_live; load_state
	local now rem t
	now=$(date +%s)
	say "== IPv4/IPv6 temporary outbound switch =="
	case $LIVE_STATE in
		none) say "  Mode        : off (native network, no restriction)" ;;
		foreign) say "  Mode        : unknown (table inet $TABLE exists but was not created by this script)" ;;
		ours)
			say "  Mode        : $LIVE_MODE ($(mode_desc "$LIVE_MODE"))"
			if [[ $LIVE_EXP =~ ^[0-9]+$ ]]; then
				rem=$((LIVE_EXP - now))
				say "  Expires at  : $(fmt_time "$LIVE_EXP")"
				if ((rem > 0)); then say "  Remaining   : $(fmt_dur "$rem")"
				else say "  Remaining   : overdue by $(fmt_dur $((-rem)))"; fi
			fi
			if systemctl is-active --quiet "$TOOL-$LIVE_ID.timer"; then
				say "  Timer       : $TOOL-$LIVE_ID.timer (active)"
			else
				say "  Timer       : MISSING"
				warn "the restriction is active but its cleanup timer is missing; run this script with 0 to remove it"
			fi
			;;
	esac
	if [[ $LIVE_STATE == ours && -n $S_ID && $S_ID != "$LIVE_ID" ]]; then
		warn "state file (id $S_ID) disagrees with the live table (id $LIVE_ID); the live table is what is in force"
	fi
	if [[ $LIVE_STATE == none && -n $S_ID ]]; then
		warn "state file says mode $S_MODE is active, but the nft table is gone (a firewall reload or 'flush ruleset' probably removed it); no restriction is in force"
	fi
	while read -r t; do
		[[ -z $t ]] && continue
		[[ $LIVE_STATE == ours && $t == "$TOOL-$LIVE_ID.timer" ]] && continue
		warn "stray timer $t (harmless: it only removes the restriction it was created for)"
	done < <(list_timers)
}

# ---------- connectivity detection ----------
declare -a CAP=() INFO=() PUBIP=()
L3WHY=
l3_check() { # family: global address + route to a public target
	local f=$1 tgt
	if [[ $f == 4 ]]; then tgt=$V4_TARGET; else tgt=$V6_TARGET; fi
	if ! ip -"$f" -o addr show scope global 2>/dev/null | grep -qv -e tentative -e dadfailed; then
		L3WHY="no usable global IPv$f address"; return 1
	fi
	if ! ip -"$f" route get "$tgt" >/dev/null 2>&1; then
		L3WHY="no IPv$f route to the internet"; return 1
	fi
	return 0
}
valid_ip() {
	if [[ $1 == 4 ]]; then [[ $2 =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]
	else [[ $2 == *:* && $2 =~ ^[0-9a-fA-F:.]+$ ]]; fi
}
probe_one() { # family kind url outfile
	local body ip
	body=$(curl -"$1" -fsS --connect-timeout "$CONNECT_TIMEOUT" --max-time "$PROBE_TIMEOUT" "$3" 2>/dev/null) || return 0
	if [[ $body == *ip=* ]]; then ip=$(sed -n 's/^ip=//p' <<<"$body" | head -n 1)
	else ip=$(head -n 1 <<<"$body" | tr -d '[:space:]'); fi
	valid_ip "$1" "$ip" || return 0
	printf '%s %s\n' "$2" "$ip" >"$4"
}
launch_probes() { # family; IP-literal endpoint tests the path, hostname endpoints also test DNS
	local f=$1 lit
	if [[ $f == 4 ]]; then lit="https://$V4_TARGET/cdn-cgi/trace"; else lit="https://[$V6_TARGET]/cdn-cgi/trace"; fi
	probe_one "$f" literal "$lit" "$PROBE_DIR/$f.1" &
	probe_one "$f" dns https://www.cloudflare.com/cdn-cgi/trace "$PROBE_DIR/$f.2" &
	probe_one "$f" dns https://api.ip.sb/ip "$PROBE_DIR/$f.3" &
	probe_one "$f" dns https://api64.ipify.org "$PROBE_DIR/$f.4" &
	probe_one "$f" dns https://icanhazip.com "$PROBE_DIR/$f.5" &
}
collect_probes() {
	local f=$1 file kind addr lit=no dns=no ip=
	for file in "$PROBE_DIR/$f".*; do
		[[ -s $file ]] || continue
		read -r kind addr <"$file"
		if [[ $kind == literal ]]; then lit=yes; else dns=yes; fi
		[[ -z $ip ]] && ip=$addr
	done
	if [[ $lit == yes || $dns == yes ]]; then
		CAP[f]=up; PUBIP[f]=$ip; INFO[f]="IP-literal test: $lit, hostname test: $dns"
	else
		CAP[f]=down; INFO[f]="address and route present, but no test endpoint answered"
	fi
}

detect_caps() {
	PROBE_DIR=$(mktemp -d "$RUNDIR/probe.XXXXXX") || die "cannot create probe directory"
	local f blocked='' rec probe=()
	if [[ $LIVE_STATE == ours ]]; then
		if [[ $LIVE_MODE == 4 ]]; then blocked=6; else blocked=4; fi
	fi
	for f in 4 6; do
		PUBIP[f]=
		if ! l3_check "$f"; then CAP[f]=down; INFO[f]=$L3WHY; continue; fi
		if [[ $f == "$blocked" ]]; then
			# The switch blocks new connections on this family, so a live test would fail.
			rec=S_CAP$f; rec=${!rec}
			if [[ -n $rec && $S_ID == "$LIVE_ID" ]]; then
				CAP[f]=$rec; INFO[f]="blocked by this switch now; native state recorded at activation: $rec"
			else
				CAP[f]=up; INFO[f]="blocked by this switch now; native state not recorded, address and route present (assumed up)"
			fi
			continue
		fi
		probe+=("$f"); launch_probes "$f"
	done
	wait
	for f in "${probe[@]}"; do collect_probes "$f"; done
	OK4=no; OK6=no
	[[ ${CAP[4]} == up ]] && OK4=yes
	[[ ${CAP[6]} == up ]] && OK6=yes
	if [[ $OK4 == yes ]]; then DEFAULT_MODE=4
	elif [[ $OK6 == yes ]]; then DEFAULT_MODE=6
	else DEFAULT_MODE=; fi
}

print_caps() {
	local f
	for f in 4 6; do
		say "  IPv$f        : ${CAP[f]}${PUBIP[f]:+  ${PUBIP[f]}}  (${INFO[f]})"
	done
	if [[ $OK4 == yes && $OK6 == yes ]]; then say "  Host type   : dual-stack"
	elif [[ $OK4 == yes ]]; then say "  Host type   : IPv4-only"
	elif [[ $OK6 == yes ]]; then say "  Host type   : IPv6-only"
	else say "  Host type   : no working family detected"; fi
}

preflight() {
	if nft list ruleset 2>/dev/null | grep -qw notrack; then
		warn "the nft ruleset contains 'notrack': untracked packets are not restricted by this switch"
	fi
	if command -v iptables-save >/dev/null 2>&1 && iptables-save -t raw 2>/dev/null | grep -q -e NOTRACK -e '--notrack'; then
		warn "iptables raw table uses NOTRACK: untracked packets are not restricted by this switch"
	fi
	if ip link show docker0 >/dev/null 2>&1; then
		warn "Docker bridge found: containers on bridge networks are routed (forward path) and are NOT restricted"
	fi
}

# ---------- prompts ----------
ask() { # varname prompt default
	local __a='' __rc=0
	if { : </dev/tty; } 2>/dev/null; then
		read -r -t "$PROMPT_TIMEOUT" -p "$2" __a </dev/tty || __rc=$?
		if ((__rc > 128)); then printf '\n(no input after %ss: using %s)\n' "$PROMPT_TIMEOUT" "$3" >&2; __a=
		elif ((__rc != 0)); then printf '\n' >&2; __a=; fi
	else
		say "(no terminal: using $3)"
	fi
	printf -v "$1" '%s' "${__a:-$3}"
}

print_options() {
	say ""
	say "Options:"
	if [[ $OK4 == yes ]]; then say "  4  keep IPv4: reject new outbound IPv6"
	else say "  4  unavailable: IPv4 is not working on this host"; fi
	if [[ $OK6 == yes ]]; then say "  6  keep IPv6: reject new outbound IPv4"
	else say "  6  unavailable: IPv6 is not working on this host"; fi
	say "  0  remove the switch now and cancel its timer"
	say "  q  quit without changes"
}

MODE='' MINUTES=''
choose_mode() {
	local ans def=${DEFAULT_MODE:-q} tries=0
	while :; do
		ask ans "Choose [4/6/0/q] (Enter or ${PROMPT_TIMEOUT}s = $def): " "$def"
		case $ans in
			4) if [[ $OK4 == yes ]]; then MODE=4; return; fi; say "option 4 is unavailable: IPv4 is not working on this host" ;;
			6) if [[ $OK6 == yes ]]; then MODE=6; return; fi; say "option 6 is unavailable: IPv6 is not working on this host" ;;
			0) MODE=0; return ;;
			q | Q) MODE=q; return ;;
			*) say "invalid choice: $ans" ;;
		esac
		((++tries >= 3)) && die "three invalid answers; nothing changed"
	done
}
choose_minutes() {
	local ans tries=0
	while :; do
		ask ans "Minutes [1-$MAX_MINUTES] (Enter or ${PROMPT_TIMEOUT}s = $DEFAULT_MINUTES): " "$DEFAULT_MINUTES"
		if valid_minutes "$ans"; then MINUTES=$((10#$ans)); return; fi
		say "invalid duration: $ans (whole minutes, 1-$MAX_MINUTES)"
		((++tries >= 3)) && die "three invalid answers; nothing changed"
	done
}

# ---------- apply / undo ----------
build_batch() { # mode id expiry
	local blocked
	if [[ $1 == 4 ]]; then blocked=ipv6; else blocked=ipv4; fi
	cat <<EOF
table inet $TABLE
delete table inet $TABLE
table inet $TABLE {
	comment "$TOOL id=$2 mode=$1 expiry=$3"
	chain output {
		type filter hook output priority filter; policy accept;
		oifname "lo" accept
		meta nfproto != $blocked accept
		ip6 daddr { fe80::/10, ff00::/8 } accept
		ip daddr { 169.254.0.0/16, 224.0.0.0/4, 255.255.255.255 } accept
		meta l4proto ipv6-icmp icmpv6 type { nd-router-solicit, nd-neighbor-solicit, nd-neighbor-advert } accept
		udp sport 68 udp dport 67 accept
		udp sport 546 udp dport 547 accept
		meta l4proto { tcp, udp } th dport { 53, 853 } accept
		ct direction original ct state new meta l4proto tcp counter reject with tcp reset
		ct direction original ct state new counter reject with icmpx type admin-prohibited
	}
}
EOF
}

APPLIED_ID='' APPLIED_EXP='' PREV_MODE=''
do_apply() { # mode minutes
	local mode=$1 minutes=$2 id now exp batch t
	write_cleanup
	exec 9>"$LOCK"
	flock -w 15 9 || die "another run holds $LOCK; nothing changed"
	read_live
	[[ $LIVE_STATE == foreign ]] && die "table inet $TABLE exists but was not created by this script; refusing to overwrite it"
	PREV_MODE=$LIVE_MODE
	id=$(od -An -N6 -tx1 /dev/urandom | tr -d ' \n')
	[[ $id =~ ^[0-9a-f]{12}$ ]] || die "cannot generate an id; nothing changed"
	now=$(date +%s); exp=$((now + minutes * 60))
	batch=$RUNDIR/batch.$id.nft
	build_batch "$mode" "$id" "$exp" >"$batch"
	if ! nft -c -f "$batch"; then rm -f "$batch"; die "nft rejected the ruleset in a dry run; nothing changed"; fi

	# Critical section: arm timer -> apply table -> record state -> retire old timers.
	trap '' INT TERM HUP
	if ! systemd-run --quiet --collect --unit="$TOOL-$id" \
		--on-active="${minutes}min" \
		--timer-property=AccuracySec=1s \
		--property=Type=oneshot \
		/bin/sh "$CLEANUP" "$id"; then
		rm -f "$batch"; die "could not arm the cleanup timer; nothing changed"
	fi
	if ! nft -f "$batch"; then
		systemctl stop "$TOOL-$id.timer" 2>/dev/null
		rm -f "$batch"; die "nft failed to apply the ruleset; nothing changed (new timer cancelled)"
	fi
	rm -f "$batch"
	write_state "$id" "$mode" "$now" "$exp" "$minutes"
	while read -r t; do
		[[ -n $t && $t != "$TOOL-$id.timer" ]] && systemctl stop "$t" 2>/dev/null
	done < <(list_timers)
	trap - INT TERM HUP
	flock -u 9; exec 9>&-
	APPLIED_ID=$id APPLIED_EXP=$exp
}

do_undo() {
	local had timers
	write_cleanup
	read_live
	[[ $LIVE_STATE == foreign ]] && die "table inet $TABLE was not created by this script; left untouched"
	had=$LIVE_STATE; timers=$(list_timers)
	sh "$CLEANUP" --force || die "cleanup failed; fallback: nft delete table inet $TABLE; systemctl stop '$TOOL-*.timer'"
	read_live
	[[ $LIVE_STATE == none ]] || die "table inet $TABLE is still present after cleanup"
	say ""
	if [[ $had == none && -z $timers ]]; then say "Nothing was active: native network unchanged."
	else say "Switch removed: native network restored, cleanup timers cancelled."; fi
}

lit_ok() {
	local u
	if [[ $1 == 4 ]]; then u="https://$V4_TARGET/cdn-cgi/trace"; else u="https://[$V6_TARGET]/cdn-cgi/trace"; fi
	curl -"$1" -fsS -o /dev/null --connect-timeout "$CONNECT_TIMEOUT" --max-time "$PROBE_TIMEOUT" "$u" 2>/dev/null
}
verify_after() {
	local allow=$1 blk
	if [[ $allow == 4 ]]; then blk=6; else blk=4; fi
	say ""
	say "Post-change check (new connections to IP literals):"
	if lit_ok "$allow"; then say "  IPv$allow        : ok (allowed)"
	else warn "new IPv$allow connection FAILED; if this persists, run this script with 0 or: sh $CLEANUP --force"; fi
	if [[ ${CAP[blk]} == up ]]; then
		if lit_ok "$blk"; then warn "new IPv$blk connection still SUCCEEDED; the restriction is not effective (untracked traffic?)"
		else say "  IPv$blk        : rejected (as intended)"; fi
	else
		say "  IPv$blk        : not available natively; nothing to verify"
	fi
}

print_applied() {
	local mode=$1 minutes=$2
	say ""
	say "== Applied =="
	say "  Mode        : $mode ($(mode_desc "$mode"))"
	[[ -n $PREV_MODE ]] && say "  Replaced    : previous mode $PREV_MODE (its deadline is cancelled)"
	say "  Duration    : $minutes min"
	say "  Expires at  : $(fmt_time "$APPLIED_EXP")"
	say "  Timer       : $TOOL-$APPLIED_ID.timer (keeps running after logout)"
	say "  Undo now    : run this script again with argument 0"
	say "  Local undo  : sh $CLEANUP --force"
	say "  Bare undo   : nft delete table inet $TABLE; systemctl stop '$TOOL-*.timer'"
	say "  Reboot      : removes everything (kernel table, transient timer, /run files)"
}

main() {
	local arg_mode='' arg_min=''
	(($# <= 2)) || { usage >&2; exit 2; }
	case ${1:-} in
		"") ;;
		-h | --help | help) usage; exit 0 ;;
		status) (($# == 1)) || { usage >&2; exit 2; }; arg_mode=status ;;
		0) (($# == 1)) || die "option 0 takes no duration"; arg_mode=0 ;;
		4 | 6) arg_mode=$1; arg_min=${2:-} ;;
		*) usage >&2; exit 2 ;;
	esac
	if [[ -n $arg_min ]] && ! valid_minutes "$arg_min"; then die "minutes must be a whole number 1-$MAX_MINUTES"; fi

	require_env
	ensure_rundir
	print_status
	say "  Checking connectivity..."
	detect_caps
	print_caps
	preflight
	[[ $arg_mode == status ]] && exit 0

	if [[ -n $arg_mode ]]; then MODE=$arg_mode; else print_options; choose_mode; fi
	case $MODE in
		q) say "Quit: nothing changed."; exit 0 ;;
		0) do_undo; exit 0 ;;
		4) [[ $OK4 == yes ]] || die "option 4 needs working IPv4 (IPv4: ${INFO[4]}); nothing changed" ;;
		6) [[ $OK6 == yes ]] || die "option 6 needs working IPv6 (IPv6: ${INFO[6]}); nothing changed" ;;
	esac
	if [[ -n $arg_mode ]]; then MINUTES=$((10#${arg_min:-$DEFAULT_MINUTES})); else choose_minutes; fi

	do_apply "$MODE" "$MINUTES"
	print_applied "$MODE" "$MINUTES"
	verify_after "$MODE"
}

main "$@"
